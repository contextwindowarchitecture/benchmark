"""S0 · Self-check (domain-2-plan.md, 8): the oracles every later suite rests on, checked before any result is trusted.

- **Graders** against hand-planted replies (s0_cases.py): format variants, wrong answers of each kind, and replies
  with nothing or too much to read.
- **Plants** from the run's own scripts: for every probe, the expected answer written several ways must grade
  correct, each stale and distractor value must grade as such, an unrelated value wrong and an empty reply unparsed;
  a record with one field changed or dropped must score one field less.
- **Generators**: every script validates against its schema, is regenerated byte for byte from its seed
  (`determinism`), has the shape every family shares (`structure`), and says in its text what its ground truth says
  (`replay`, conversations/check.py).

The fact-in-payload oracle against planted omissions, the baselines against hand-computed payloads and the request
canon's determinism join S0 with the phases that build them (P1 to P3).
"""
from __future__ import annotations

import json
from collections import defaultdict

from cwabench.rundir import now

from .. import metrics, output
from ..conversations import check, generate
from ..conversations.names import number
from ..grading import grade
from . import SuiteContext, SuiteResult, finding
from .s0_cases import CASES

ID = "S0"
TITLE = "Self-check"


def _plants(probe: dict) -> list[tuple[str, str, str, float]]:
    """(plant id, reply, verdict, score) for one probe's answer."""
    answer = probe["answer"]
    if answer["kind"] == "number":
        expected = int(answer["expected"])
        taken = {int(v) for v in (answer["expected"], *answer["stale"], *answer["distractors"])}
        unrelated = next(v for v in range(expected + 1, expected + 10_000) if v not in taken)
        plants = [("expected", answer["expected"], "correct", 1.0),
                  ("expected-grouped", number(expected), "correct", 1.0),
                  ("expected-sentence", f"It is {number(expected)} now.", "correct", 1.0),
                  ("unrelated", number(unrelated), "wrong", 0.0),
                  ("empty", "", "unparsed", 0.0)]
        plants += [(f"stale-{i}", number(int(v)), "stale", 0.0) for i, v in enumerate(answer["stale"])]
        plants += [(f"distractor-{i}", number(int(v)), "distractor", 0.0) for i, v in enumerate(answer["distractors"])]
        return plants
    fields = answer["fields"]
    expected = {name: (int(spec["expected"]) if spec["kind"] == "number" and spec["expected"] is not None
                       else spec["expected"]) for name, spec in fields.items()}
    exact = json.dumps(expected)
    plants = [("expected", exact, "correct", 1.0), ("expected-fenced", f"```json\n{exact}\n```", "correct", 1.0),
              ("empty", "", "unparsed", 0.0)]
    share = (len(fields) - 1) / len(fields)
    first = next(iter(fields))
    dropped = {k: v for k, v in expected.items() if k != first}
    plants.append(("dropped-key", json.dumps(dropped), "wrong", share))
    known = [name for name, value in expected.items() if value is not None]
    if known:
        changed = dict(expected)
        changed[known[0]] = (changed[known[0]] + 1) if isinstance(changed[known[0]], int) else "Nowhere"
        plants.append(("changed-field", json.dumps(changed), "wrong", share))
    return plants


def run(ctx: SuiteContext) -> SuiteResult:
    started = now()
    rows, findings = [], []
    tally = defaultdict(lambda: [0, 0])  # check → [passed, total]

    def record(case_id: str, check_name: str, subject: str, ok: bool, expected, actual, detail: str | None = None,
               conversation: str | None = None) -> None:
        tally[check_name][0] += ok
        tally[check_name][1] += 1
        rows.append({
            "$schema": output.schema_name("self-check"),
            "run_id": ctx.run.run_id,
            "suite": ID,
            "case_id": case_id,
            "check": check_name,
            "subject": subject,
            "conversation": conversation,
            "status": "pass" if ok else "fail",
            "expected": expected,
            "actual": actual,
            "detail": detail,
        })
        if not ok:
            signature = {"suite": ID, "check": check_name, "case_id": case_id}
            findings.append(finding(ctx, ID, signature, case_id=case_id, oracle="self-check", checks=[check_name],
                                    summary=f"S0 {check_name} {case_id}: {detail or f'{actual} ≠ {expected}'}"))

    def graded(case_id: str, check_name: str, answer: dict, reply: str, verdict: str, score: float,
               conversation: str | None = None) -> None:
        got = grade(answer, reply)
        ok = got.verdict == verdict and abs(got.score - score) < 1e-9
        record(case_id, check_name, answer["kind"], ok, {"verdict": verdict, "score": score},
               {"verdict": got.verdict, "score": got.score}, None if ok else got.detail, conversation)

    for case_id, answer, reply, verdict, score in CASES:
        graded(case_id, "grader", answer, reply, verdict, score)

    every = ctx.config.checkpoint_every
    for family, scripts in ctx.conversations.items():
        parameters = ctx.config.families[family].parameters
        seed = ctx.config.families[family].seed
        for script in scripts:
            cid = script["conversation_id"]
            index = int(cid.rsplit("-", 1)[1])
            try:
                output.validate(script)
                record(f"{cid}/schema", "schema", family, True, None, None, conversation=cid)
            except output.OutputError as error:
                record(f"{cid}/schema", "schema", family, False, None, None, str(error)[:300], cid)
            again = generate(family, seed, script["turn_count"], index, every, parameters)
            same = output.dumps(again, compact=True) == output.dumps(script, compact=True)
            record(f"{cid}/determinism", "determinism", family, same, None, None,
                   None if same else "regenerating from the seed gives other bytes", cid)
            for name, problems in (("structure", check.structure(script)), ("replay", check.replay(script))):
                record(f"{cid}/{name}", name, family, not problems, None, None,
                       "; ".join(problems)[:500] or None, cid)
            for probe in script["probes"]:
                for plant, reply, verdict, score in _plants(probe):
                    graded(f"{cid}/{probe['probe_id']}/{plant}", "plant", probe["answer"], reply, verdict, score, cid)

    ctx.run.write_jsonl(f"suites/{ID}/results.jsonl", rows, "self-check", "One row per self-check: graders, plants, "
                        "and the generators' schema, determinism, structure and replay checks")
    labels = {"grader": "Planted replies graded as expected", "plant": "Probe plants graded as expected",
              "schema": "Scripts valid against their schema", "determinism": "Scripts regenerated byte for byte",
              "structure": "Scripts with the shared shape", "replay": "Scripts whose text says their ground truth"}
    suite_metrics = [metrics.rate(f"s0.{name}", labels[name], *tally[name], suite=ID) for name in labels]
    status = "pass" if all(m["status"] in ("pass", "na") for m in suite_metrics) and not findings else "fail"
    summary_path = f"suites/{ID}/summary.json"
    ctx.run.write_json(summary_path, {
        "$schema": output.schema_name("suite-summary"),
        "run_id": ctx.run.run_id,
        "suite": ID,
        "title": TITLE,
        "status": status,
        "started_at": started,
        "finished_at": now(),
        "requirements": [],
        "corpora": [{"id": family, "count": len(scripts)} for family, scripts in ctx.conversations.items()],
        "adapters": [],
        "metrics": suite_metrics,
        "files": {"results": f"suites/{ID}/results.jsonl", "findings": "findings.jsonl"},
        "self_check": {name: {"passed": passed, "total": total} for name, (passed, total) in sorted(tally.items())},
    }, "S0's checks of the graders and the generators")
    return SuiteResult(ID, TITLE, status, summary_path, suite_metrics, findings)
